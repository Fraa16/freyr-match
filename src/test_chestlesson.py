import os, sys, json
from playwright.sync_api import sync_playwright
D = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, D)
from fontfix import fonts
H = open(D + '/harness.js').read()
LEARN = json.dumps({k: True for k in ['basics', 'cat', 'laser', 'milk', 'nip', 'boxes', 'bowl']})
with sync_playwright() as p:
    b = p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
    pg = b.new_page(viewport={'width': 390, 'height': 844}, device_scale_factor=2); errs = []
    import veteran as _v; _v.seen_intro(pg)
    pg.on('pageerror', lambda e: errs.append(str(e)))
    # A: win level 7, Freyr walks on, the chest gets its lesson, then it opens
    pg.goto('file://' + D + '/game.html'); pg.evaluate('localStorage.clear()')
    pg.evaluate(f"localStorage.setItem('wm-level', 7); localStorage.setItem('wm-learn', '{LEARN}'); localStorage.setItem('wm-hearts', JSON.stringify({{1:3,2:3,3:3,4:3,5:2,6:2}}))")
    pg.reload(); pg.wait_for_timeout(900); fonts(pg)
    pg.evaluate("""async () => { mapSkip = true; for (let i = 0; i < 160 && mapAnimating; i++) await new Promise(r => setTimeout(r, 50)); }"""); pg.wait_for_timeout(300)
    print('map at 7: chest button hidden', pg.evaluate("document.getElementById('mChest').hidden"), 'tut', pg.evaluate('tut && tut.id'))
    pg.screenshot(path=D + '/cl_map7.png')
    pg.evaluate("openLevel(7)"); pg.wait_for_timeout(600)
    pg.add_script_tag(content=H); pg.click('#introBtn'); pg.wait_for_timeout(600); pg.evaluate('T_waitIdle()')
    print('lesson on 7 (bowl already learnt):', pg.evaluate('tut && tut.id'))
    pg.evaluate("() => { T_setup(1, [[5,1],[5,2],[6,3]]); T_goalNext(); moves = 12; updateHud(); trySwap(6,3,5,3); }")
    pg.wait_for_function('document.getElementById("endOv").classList.contains("show")', timeout=60000); pg.wait_for_timeout(1500)
    print('win card heart line:', pg.evaluate("document.getElementById('heartTotal').textContent"), '| maxLevel', pg.evaluate('maxLevel'))
    pg.click('#endBtn')
    pg.wait_for_function('tut && tut.id === "chest" && !document.getElementById("coach").hidden', timeout=30000); pg.wait_for_timeout(700)
    pg.screenshot(path=D + '/cl_lesson.png')
    print('chest lesson text:', pg.evaluate("tutEls.text.textContent"))
    pg.click('#coach .ccard button')
    pg.wait_for_function('document.getElementById("chestOv").classList.contains("show")', timeout=30000); pg.wait_for_timeout(700)
    pg.screenshot(path=D + '/cl_chest.png')
    print('learnt chest', pg.evaluate('learnt.chest'), 'coach hidden', pg.evaluate("document.getElementById('coach').hidden"))
    pg.click('#chestBtn'); pg.wait_for_timeout(1200); pg.click('#chestBtn')
    pg.wait_for_function('document.getElementById("introOv").classList.contains("show")', timeout=20000); pg.wait_for_timeout(500)
    print('then the next level card:', pg.evaluate('level'), pg.evaluate('cfg.intro'))
    pg.screenshot(path=D + '/cl_intro8.png')
    # B: coming back to the map later still shows the lesson once
    pg.goto('file://' + D + '/game.html'); pg.evaluate('localStorage.clear()')
    pg.evaluate(f"localStorage.setItem('wm-level', 9); localStorage.setItem('wm-learn', '{LEARN}')")
    pg.reload(); pg.wait_for_timeout(2200)
    print('B: lesson on plain map load:', pg.evaluate('tut && tut.id'))
    pg.click('#coach .ccard button'); pg.wait_for_timeout(300)
    print('B: learnt', pg.evaluate('learnt.chest'))
    pg.reload(); pg.wait_for_timeout(2200)
    print('B: after reload, lesson again?', pg.evaluate('tut && tut.id'))
    print('errors', errs)
    b.close()
