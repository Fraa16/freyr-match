import os, json
from playwright.sync_api import sync_playwright
D = os.path.dirname(os.path.abspath(__file__))
H = open(D + '/harness.js').read()
with sync_playwright() as p:
    b = p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
    pg = b.new_page(viewport={'width': 390, 'height': 844}, device_scale_factor=2); errs = []; __import__('veteran').veteran(pg)
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('file://' + D + '/game.html')
    pg.evaluate('() => { localStorage.clear(); localStorage.setItem("wm-level", 4); localStorage.setItem("wm-hearts", JSON.stringify({1:1,2:2,3:3})); localStorage.setItem("wm-treats", 5); }')
    pg.reload(); pg.wait_for_timeout(900)
    pg.click('.mnode[data-l="1"]'); pg.wait_for_timeout(600)
    print('replay intro best hearts', pg.evaluate('document.querySelectorAll("#introBest svg.on").length'), 'level', pg.evaluate('level'))
    pg.click('#introBtn'); pg.wait_for_timeout(600)
    pg.add_script_tag(content=H); pg.evaluate('T_waitIdle()')
    pg.evaluate('''() => { T_setup(1, [[5,1],[5,2],[6,3]]); T_goalNext(); moves = 15; updateHud(); trySwap(6,3,5,3); }''')
    pg.wait_for_function('document.getElementById("endOv").classList.contains("show")', timeout=90000)
    pg.wait_for_timeout(1200)
    print('replay win: treats', pg.evaluate('treats'), 'maxLevel', pg.evaluate('maxLevel'), 'jar', pg.evaluate('document.getElementById("jarLine").innerText.replace(/\\n/g, " | ")'), 'prog', pg.evaluate('JSON.stringify(mapProg)'))
    pg.click('#endBtn'); pg.wait_for_timeout(2600)
    print('after: hearts on node 1', pg.evaluate('document.querySelectorAll(\'.mnode[data-l="1"] .mh svg.on\').length'), 'intro open', pg.evaluate('document.getElementById("introOv").classList.contains("show")'), 'freyr at', pg.evaluate('document.getElementById("mFreyr").style.top'))
    pg.screenshot(path=D + '/replay.png')
    print('errors', errs)
    b.close()
