import os, sys
from playwright.sync_api import sync_playwright
D = os.path.dirname(os.path.abspath(__file__))
GAME = 'file://' + D + '/' + (sys.argv[1] if len(sys.argv) > 1 else 'game.html')
H = open(D + '/harness.js').read()
W, HH = (int(x) for x in (sys.argv[2] if len(sys.argv) > 2 else '390x844').split('x'))
def shot(pg, name): pg.screenshot(path=D + '/j_' + name + '.png')
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={'width': W, 'height': HH}, device_scale_factor=2); __import__('veteran').veteran(pg)
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(GAME); pg.evaluate('localStorage.clear(); localStorage.setItem("wm-level", 25)'); pg.reload(); pg.wait_for_timeout(900)
    print('L25 intro: legend shown', pg.evaluate('!document.getElementById("legendWrap").hidden'), 'boosts shown', pg.evaluate('!document.getElementById("boostWrap").hidden'))
    pg.evaluate("""async () => { mapSkip = true; for (let i = 0; i < 120 && mapAnimating; i++) await new Promise(r => setTimeout(r, 50)); if (!document.getElementById('introOv').classList.contains('show')) openLevel(maxLevel); }"""); pg.wait_for_timeout(500); pg.click('#introBtn'); pg.wait_for_timeout(400)
    pg.add_script_tag(content=H); pg.evaluate('T_waitIdle()')
    # 1) win with 9 moves left
    pg.evaluate('''() => { T_setup(1, [[5,1],[5,2],[6,3]]); T_goalNext(); moves = 10; updateHud(); window.__d = false; trySwap(6,3,5,3).then(() => window.__d = true); }''')
    pg.wait_for_function('window.__d === true', timeout=60000); pg.wait_for_timeout(700)
    print('after win: treats', pg.evaluate('treats'), 'stored', pg.evaluate('localStorage.getItem("wm-treats")'), 'jar line:', pg.evaluate('document.getElementById("jarLine").innerText.replace(/\\n/g, " | ")'))
    shot(pg, 'win')
    # 2) next level with enough treats: boosters on the card
    pg.evaluate('treats = 50; saveJar()')
    pg.click('#endBtn'); pg.wait_for_function('document.getElementById("introOv").classList.contains("show")', timeout=20000); pg.wait_for_timeout(300)
    print('L26 intro: boosts shown', pg.evaluate('!document.getElementById("boostWrap").hidden'), 'disabled', pg.evaluate('[...document.querySelectorAll(".boost")].map(b => b.dataset.id + ":" + b.disabled)'))
    pg.click('.boost[data-id="laser"]'); pg.wait_for_timeout(150)
    shot(pg, 'boosts')
    pg.evaluate("""async () => { mapSkip = true; for (let i = 0; i < 120 && mapAnimating; i++) await new Promise(r => setTimeout(r, 50)); if (!document.getElementById('introOv').classList.contains('show')) openLevel(maxLevel); }"""); pg.wait_for_timeout(500); pg.click('#introBtn'); pg.wait_for_timeout(900); pg.evaluate('T_waitIdle()')
    print('after start with laser: treats', pg.evaluate('treats'), 'lasers on board', pg.evaluate('countOnBoard(x => x.type === "laser")'))
    shot(pg, 'boosted')
    # 3) lose -> rescue -> lose again (no second rescue)
    pg.evaluate('''() => { T_setup(1, [[5,1],[5,2],[4,3]]); score = 0; moves = 1; for (const g of goals) if (g.kind === 'collect') g.left = 99; updateHud(); window.__d = false; trySwap(4,3,5,3).then(() => window.__d = true); }''')
    pg.wait_for_function('window.__d === true', timeout=60000); pg.wait_for_timeout(500)
    print('lost: end shown', pg.evaluate('document.getElementById("endOv").classList.contains("show")'), 'rescue visible', pg.evaluate('!document.getElementById("rescueBtn").hidden'))
    shot(pg, 'lost')
    pg.click('#rescueBtn'); pg.wait_for_timeout(400)
    print('rescued: moves', pg.evaluate('moves'), 'treats', pg.evaluate('treats'), 'busy', pg.evaluate('busy'), 'overlay', pg.evaluate('document.getElementById("endOv").classList.contains("show")'))
    pg.evaluate('''() => { T_setup(1, [[5,1],[5,2],[4,3]]); moves = 1; updateHud(); window.__d = false; trySwap(4,3,5,3).then(() => window.__d = true); }''')
    pg.wait_for_function('window.__d === true', timeout=60000); pg.wait_for_timeout(400)
    print('lost again: rescue visible', pg.evaluate('!document.getElementById("rescueBtn").hidden'), 'disabled', pg.evaluate('document.getElementById("rescueBtn").disabled'), pg.evaluate('document.getElementById("rescueBtn").textContent'))
    pg.click('#endBtn'); pg.wait_for_timeout(500); pg.evaluate("""async () => { mapSkip = true; for (let i = 0; i < 120 && mapAnimating; i++) await new Promise(r => setTimeout(r, 50)); if (!document.getElementById('introOv').classList.contains('show')) openLevel(maxLevel); }"""); pg.wait_for_timeout(500); pg.click('#introBtn'); pg.wait_for_timeout(400)
    # 4) outfits
    pg.evaluate('treats = 35; saveJar()')
    pg.click('#pauseBtn'); pg.wait_for_timeout(300); pg.click('#pCat'); pg.wait_for_timeout(300)
    print('outfits disabled', pg.evaluate('[...document.querySelectorAll(".outfit")].map(b => b.dataset.id + ":" + b.disabled)'))
    pg.click('.outfit[data-id="bow"]'); pg.wait_for_timeout(150)
    print('first tap:', pg.evaluate('document.querySelector(".outfit[data-id=bow] small").textContent'), 'treats', pg.evaluate('treats'))
    pg.click('.outfit[data-id="bow"]'); pg.wait_for_timeout(200)
    print('second tap: wear', pg.evaluate('wear'), 'owned', pg.evaluate('owned'), 'treats', pg.evaluate('treats'))
    shot(pg, 'outfits')
    pg.click('#setDone'); pg.wait_for_timeout(300)
    pg.evaluate('''() => { grid[4][4] = Object.assign(mk('cat'), {dir: 'h'}); render(false); }'''); pg.wait_for_timeout(200)
    shot(pg, 'wearing')
    print('mascot has bow', pg.evaluate('!!mascot.querySelector(".acc")'), 'cat tile has bow', pg.evaluate('!!els.get(grid[4][4].id).querySelector(".acc")'))
    # 5) reload keeps everything
    pg.reload(); pg.wait_for_timeout(800)
    print('after reload: treats', pg.evaluate('treats'), 'wear', pg.evaluate('wear'), 'level', pg.evaluate('level'))
    print('errors:', errs)
    b.close()
